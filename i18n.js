export const LANGUAGES = { en: 'English', vi: 'Tiếng Việt' };

let current = 'en';

/** The language the browser prefers, limited to the ones we have. */
export function detectLanguage() {
  const first = (navigator.languages && navigator.languages[0]) || navigator.language || '';
  return first.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

/** Applies a setting value: 'en', 'vi', or '' for the browser's language. */
export function setLanguage(choice) {
  current = STRINGS[choice] ? choice : detectLanguage();
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  return current;
}

export function language() {
  return current;
}

export function t(key, params = {}) {
  const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/** Fills elements marked with data-i18n (text), data-i18n-placeholder, -title and -aria-label. */
export function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
}

